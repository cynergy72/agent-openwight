CREATE MULTISET TABLE SALES_DB.CUSTOMER ,NO FALLBACK (
    CUST_ID      INTEGER NOT NULL,
    CUST_NM      VARCHAR(100) CHARACTER SET UNICODE NOT CASESPECIFIC,
    GRADE_CD     CHAR(1),
    JOIN_DT      DATE FORMAT 'YYYY-MM-DD',
    REGION_CD    CHAR(2)
) UNIQUE PRIMARY INDEX (CUST_ID);

COMMENT ON TABLE SALES_DB.CUSTOMER IS '고객 마스터';
COMMENT ON COLUMN SALES_DB.CUSTOMER.CUST_ID IS '고객ID';
COMMENT ON COLUMN SALES_DB.CUSTOMER.CUST_NM IS '고객명';
COMMENT ON COLUMN SALES_DB.CUSTOMER.GRADE_CD IS '고객등급코드 (V:VIP, G:골드, S:실버, N:일반)';
COMMENT ON COLUMN SALES_DB.CUSTOMER.JOIN_DT IS '가입일자';
COMMENT ON COLUMN SALES_DB.CUSTOMER.REGION_CD IS '지역코드';

CREATE MULTISET TABLE SALES_DB.SALES_TXN ,NO FALLBACK (
    TXN_ID       BIGINT NOT NULL,
    CUST_ID      INTEGER NOT NULL,
    PROD_ID      INTEGER NOT NULL,
    SALE_DT      DATE FORMAT 'YYYY-MM-DD' NOT NULL,
    QTY          INTEGER,
    SALE_AMT     DECIMAL(18,2),
    DISC_AMT     DECIMAL(18,2),
    CHANNEL_CD   CHAR(2)
) PRIMARY INDEX (CUST_ID)
PARTITION BY RANGE_N(SALE_DT BETWEEN DATE '2020-01-01' AND DATE '2030-12-31' EACH INTERVAL '1' MONTH);

COMMENT ON TABLE SALES_DB.SALES_TXN IS '판매 거래 내역 (매출)';
COMMENT ON COLUMN SALES_DB.SALES_TXN.TXN_ID IS '거래ID';
COMMENT ON COLUMN SALES_DB.SALES_TXN.CUST_ID IS '고객ID';
COMMENT ON COLUMN SALES_DB.SALES_TXN.PROD_ID IS '상품ID';
COMMENT ON COLUMN SALES_DB.SALES_TXN.SALE_DT IS '판매일자 (파티션 컬럼)';
COMMENT ON COLUMN SALES_DB.SALES_TXN.QTY IS '판매수량';
COMMENT ON COLUMN SALES_DB.SALES_TXN.SALE_AMT IS '판매금액(매출액)';
COMMENT ON COLUMN SALES_DB.SALES_TXN.DISC_AMT IS '할인금액';
COMMENT ON COLUMN SALES_DB.SALES_TXN.CHANNEL_CD IS '판매채널코드 (ON:온라인, OF:오프라인)';

CREATE MULTISET TABLE SALES_DB.PRODUCT ,NO FALLBACK (
    PROD_ID      INTEGER NOT NULL,
    PROD_NM      VARCHAR(200) CHARACTER SET UNICODE,
    CATEGORY_CD  VARCHAR(10),
    UNIT_PRICE   DECIMAL(18,2)
) UNIQUE PRIMARY INDEX (PROD_ID);

COMMENT ON TABLE SALES_DB.PRODUCT IS '상품 마스터';
COMMENT ON COLUMN SALES_DB.PRODUCT.PROD_NM IS '상품명';
COMMENT ON COLUMN SALES_DB.PRODUCT.CATEGORY_CD IS '상품카테고리코드';
COMMENT ON COLUMN SALES_DB.PRODUCT.UNIT_PRICE IS '단가';
